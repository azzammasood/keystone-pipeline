"""Generated ODCS contracts for the datasets that have no hand-written one.

Hand-written contracts live in `contracts/` (silver GH Archive tables). Everything else is
generated here and committed to `metadata/contracts/`: OSV silver tables (types from the
pydantic-derived Arrow schemas), the free rollup tables (types from the DuckDB file) and every
dbt model and seed (types from `catalog.json`, descriptions from the dbt YAML, `required` from
`not_null` tests). A commit is the review: `keystone metadata contracts --check` regenerates
them and fails when the committed files differ (a schema or description changed without the
contract), and `keystone quality contracts` tests them against the data with datacontract-cli.
"""

import json
from pathlib import Path
from typing import Any

import duckdb
import pyarrow as pa
import yaml

from keystone.export.meta import Metadata

OUT_DIR_NAME = "contracts"
ODCS_VERSION = "v3.1.0"
SKIP_TEST = "skip: view over the attached rollup database; checked by dbt build"

# Arrow type -> (ODCS logical type, physical type as the hand-written contracts spell it).
_ARROW = {
    "string": ("string", "STRING"),
    "large_string": ("string", "STRING"),
    "int64": ("integer", "INT64"),
    "int32": ("integer", "INT32"),
    "bool": ("boolean", "BOOLEAN"),
    "double": ("number", "DOUBLE"),
    "date32[day]": ("date", "DATE"),
}


def _logical(physical: str) -> str:
    t = physical.upper()
    if t.startswith("TIMESTAMP"):
        return "timestamp"
    if t == "DATE":
        return "date"
    if t in ("BOOLEAN", "BOOL"):
        return "boolean"
    if t in ("BIGINT", "INTEGER", "SMALLINT", "TINYINT", "HUGEINT", "UBIGINT", "INT64", "INT32"):
        return "integer"
    if t.startswith(("DOUBLE", "FLOAT", "DECIMAL", "REAL")):
        return "number"
    return "string"


def _arrow_type(t: pa.DataType) -> tuple[str, str]:
    if pa.types.is_timestamp(t):
        return "timestamp", "TIMESTAMP"
    return _ARROW[str(t)]  # an unmapped type fails loudly rather than guessing


def _contract(
    meta: Metadata,
    cid: str,
    name: str,
    dataset_id: str,
    table: str,
    description: str,
    server: dict[str, Any],
    columns: list[dict[str, Any]],
) -> dict[str, Any]:
    ds = meta.dataset(dataset_id)
    return {
        "apiVersion": ODCS_VERSION,
        "kind": "DataContract",
        "id": cid,
        "name": name,
        "version": "1.0.0",
        "status": "active",
        "domain": ds.domain,
        "tags": [f"layer:{ds.layer}", f"classification:{ds.classification}"],
        "description": {
            "purpose": description,
            "usage": "Generated by `keystone metadata contracts` (export/contracts.py).",
        },
        "team": [{"username": meta.owner_id, "role": "owner"}],
        "slaProperties": [
            {"property": "freshness", "value": ds.freshness_sla_hours, "unit": "h"},
        ],
        "servers": [server],
        "schema": [
            {
                "name": table,
                "physicalName": table,
                "physicalType": "table",
                "logicalType": "object",
                "description": description,
                "properties": columns,
            }
        ],
    }


def _column(
    name: str, logical: str, physical: str, description: str, required: bool
) -> dict[str, Any]:
    col: dict[str, Any] = {
        "name": name,
        "logicalType": logical,
        "physicalType": physical,
        "description": description,
    }
    if required:
        col["required"] = True
    return col


def osv_contracts(meta: Metadata) -> dict[str, dict[str, Any]]:
    from keystone.parsers.parquet import OSV_QUARANTINE_SCHEMA, OSV_SCHEMAS

    tables = {**OSV_SCHEMAS, "quarantine": OSV_QUARANTINE_SCHEMA}
    out = {}
    for table, schema in tables.items():
        docs_key = f"osv_{table}"
        silver = "quarantine/osv" if table == "quarantine" else f"silver/osv/{table}"
        dataset_id = f"file://keystone/{silver}"
        cols = []
        for f in schema:
            logical, physical = _arrow_type(f.type)
            cols.append(
                _column(
                    f.name, logical, physical, meta.column_doc(docs_key, f.name), not f.nullable
                )
            )
        out[f"{docs_key}.odcs.yaml"] = _contract(
            meta,
            f"keystone-{docs_key.replace('_', '-')}",
            meta.dataset(dataset_id).title,
            dataset_id,
            table,
            meta.dataset(dataset_id).description,
            {
                "server": "local",
                "type": "local",
                "format": "parquet",
                "path": f"data/{silver}/*.parquet",
            },
            cols,
        )
    return out


def rollup_contracts(meta: Metadata, rollup_db: Path) -> dict[str, dict[str, Any]]:
    out = {}
    con = duckdb.connect(str(rollup_db), read_only=True)
    try:
        for table in ("repo_hour", "repo_actor_day"):
            dataset_id = f"duckdb://keystone/rollup.main.{table}"
            cols = [
                _column(r[0], _logical(r[1]), r[1], meta.column_doc(table, r[0]), r[2] == "NO")
                for r in con.execute(f"DESCRIBE {table}").fetchall()
            ]
            out[f"rollup_{table}.odcs.yaml"] = _contract(
                meta,
                f"keystone-rollup-{table.replace('_', '-')}",
                meta.dataset(dataset_id).title,
                dataset_id,
                table,
                meta.dataset(dataset_id).description,
                {
                    "server": "local",
                    "type": "duckdb",
                    "database": "data/rollup/rollup.duckdb",
                    "schema": "main",
                },
                cols,
            )
    finally:
        con.close()
    return out


def _not_null_columns(manifest: dict[str, Any], unique_id: str) -> set[str]:
    out = set()
    for node in manifest["nodes"].values():
        if node["resource_type"] != "test" or unique_id not in node.get("depends_on", {}).get(
            "nodes", []
        ):
            continue
        meta = node.get("test_metadata") or {}
        if meta.get("name") == "not_null" and node.get("column_name"):
            out.add(node["column_name"])
    return out


def dbt_contracts(meta: Metadata, target_dir: Path) -> dict[str, dict[str, Any]]:
    manifest = json.loads((target_dir / "manifest.json").read_text("utf-8"))
    catalog = json.loads((target_dir / "catalog.json").read_text("utf-8"))
    out = {}
    for uid, node in sorted(manifest["nodes"].items()):
        if node["resource_type"] not in ("model", "seed"):
            continue
        cat = catalog["nodes"].get(uid)
        if cat is None:
            continue
        schema, name = node["schema"], node["name"]
        dataset_id = f"duckdb://keystone/keystone.{schema}.{name}"
        required = _not_null_columns(manifest, uid)
        docs = node.get("columns", {})
        cols = [
            _column(
                c["name"],
                _logical(c["type"]),
                c["type"],
                (docs.get(c["name"]) or {}).get("description", ""),
                c["name"] in required,
            )
            for c in sorted(cat["columns"].values(), key=lambda c: c["index"])
        ]
        contract = _contract(
            meta,
            f"keystone-dbt-{schema}-{name}".replace("_", "-"),
            f"{schema}.{name}",
            dataset_id,
            name,
            node.get("description", "").strip(),
            {
                "server": "local",
                "type": "duckdb",
                "database": "data/warehouse/keystone.duckdb",
                "schema": schema,
            },
            cols,
        )
        attached = any(
            d.startswith("source.keystone.rollup.")
            for d in node.get("depends_on", {}).get("nodes", [])
        )
        if node["config"].get("materialized") == "view" and attached:
            # datacontract-cli opens the warehouse file alone, without dbt's ATTACH of the
            # rollup database, so this view cannot be read there; dbt build tests it instead.
            contract["customProperties"] = [{"property": "keystoneTest", "value": SKIP_TEST}]
        out[f"dbt_{schema}_{name}.odcs.yaml"] = contract
    return out


def generate(meta: Metadata, root: Path) -> dict[str, str]:
    """File name -> YAML text of every generated contract."""
    from keystone.warehouse.dbt import WarehousePaths

    paths = WarehousePaths(root)
    meta.register_dbt(paths.target_dir)
    contracts = {
        **osv_contracts(meta),
        **rollup_contracts(meta, paths.rollup_db),
        **dbt_contracts(meta, paths.target_dir),
    }
    return {
        name: yaml.safe_dump(c, sort_keys=False, allow_unicode=True, width=100)
        for name, c in sorted(contracts.items())
    }
